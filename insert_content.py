def tc(label, content_lines, label_fill, label_color, label_bold=True, right_fill=None):
    b = '<w:b/>' if label_bold else ''
    shd_right = f'<w:shd w:val="clear" w:color="auto" w:fill="{right_fill}"/>' if right_fill else ''
    marg = '<w:tcMar><w:top w:w="80" w:type="dxa"/><w:left w:w="120" w:type="dxa"/><w:bottom w:w="80" w:type="dxa"/><w:right w:w="120" w:type="dxa"/></w:tcMar>'

    left_cell = f'''<w:tc>
        <w:tcPr><w:tcW w:w="2200" w:type="dxa"/><w:shd w:val="clear" w:color="auto" w:fill="{label_fill}"/>{marg}<w:vAlign w:val="center"/></w:tcPr>
        <w:p><w:pPr><w:jc w:val="center"/><w:spacing w:after="0"/></w:pPr><w:r><w:rPr>{b}<w:rFonts w:hint="eastAsia"/><w:color w:val="{label_color}"/></w:rPr><w:t>{esc(label)}</w:t></w:r></w:p>
      </w:tc>'''

    right_paras = ''
    for i, line in enumerate(content_lines):
        sa = '60' if i < len(content_lines)-1 else '0'
        right_paras += f'<w:p><w:pPr><w:spacing w:after="{sa}"/></w:pPr><w:r><w:rPr><w:rFonts w:hint="eastAsia"/><w:color w:val="1F1F1F"/></w:rPr><w:t>{esc(line)}</w:t></w:r></w:p>'

    right_cell = f'''<w:tc>
        <w:tcPr><w:tcW w:w="6106" w:type="dxa"/>{shd_right}{marg}</w:tcPr>
        {right_paras}
      </w:tc>'''

    return f'<w:tr>{left_cell}{right_cell}</w:tr>\n'

