# ── XML helpers ──────────────────────────────────────────────
def esc(t):
    return t.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')

def rpr(bold=False, color='1F1F1F', extra=''):
    b = '<w:b/>' if bold else ''
    return f'<w:rPr>{b}<w:rFonts w:hint="eastAsia"/><w:color w:val="{color}"/>{extra}</w:rPr>'

def para(text, bold=False, indent=False, center=False, sa=120, sb=0, color='1F1F1F'):
    jc = '<w:jc w:val="center"/>' if center else ''
    ppr_rpr = rpr(bold=bold, color=color)
    pPr = f'<w:pPr><w:pStyle w:val="Default"/>{jc}<w:spacing w:before="{sb}" w:after="{sa}"/><w:rPr>{("<w:b/>" if bold else "")}<w:color w:val="{color}"/></w:rPr></w:pPr>'
    prefix = esc('　　') if indent else ''
    r_rpr = rpr(bold=bold, color=color)
    return f'<w:p>{pPr}<w:r>{r_rpr}<w:t xml:space="preserve">{prefix}{esc(text)}</w:t></w:r></w:p>\n'

def h1(t): return para(t, bold=True, sa=80, sb=160)
def h2(t): return para(t, bold=True, sa=60, sb=120)
def h3(t): return para(t, sa=60, sb=80)
def body(t): return para(t, indent=True, sa=120)
def sp(): return '<w:p><w:pPr><w:spacing w:after="80"/></w:pPr></w:p>\n'
def pb(): return '<w:p><w:r><w:br w:type="page"/></w:r></w:p>\n'

